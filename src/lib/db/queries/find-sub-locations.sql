SELECT
  FR.FIRST_FEATURE_PK AS PREMISES_FEATURE_PK,
  SL.FEATURE_PK,
  F.FEATURE_NAME,
  SL.SUB_LOCATION_TYPE,
  SL.USABLE_AREA,
  SL.USUAL_STOCK_QUANTITY,
  SL.BROILER_STOCKG_DENSITY_RANGE,
  FR.FEATURE_RELATN_FROM_DATE,
  FS.FEATURE_STATUS_CODE,
  FS.FEATURE_STATE_REASON_CODE,
  FS.FEATURE_STATE_FROM_DTTM
FROM AHBRP.FEATURE_RELATIONSHIP FR
JOIN AHBRP.SUB_LOCATION SL
  ON SL.FEATURE_PK = FR.SECOND_FEATURE_PK
LEFT JOIN AHBRP.FEATURE F
  ON F.FEATURE_PK = SL.FEATURE_PK
LEFT JOIN AHBRP.FEATURE_STATE FS
  ON FS.FEATURE_PK = SL.FEATURE_PK
 AND FS.FEATURE_STATE_TO_DTTM IS NULL
WHERE FR.FIRST_FEATURE_PK IN (__FEATURE_KEYS__)
  AND FR.FEATURE_RELATIONSHIP_TYPE = 'CONTAINS'
  AND FR.FEATURE_RELATN_TO_DATE IS NULL
ORDER BY FR.FIRST_FEATURE_PK, SL.FEATURE_PK
