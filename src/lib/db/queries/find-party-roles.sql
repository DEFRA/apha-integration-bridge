WITH
ROLE_NAME AS (
  SELECT
    RDC.CODE,
    RDCD.SHORT_DESCRIPTION
  FROM AHBRP.REF_DATA_SET RDS
  JOIN AHBRP.REF_DATA_CODE RDC
    ON RDC.REF_DATA_SET_PK = RDS.REF_DATA_SET_PK
  JOIN AHBRP.REF_DATA_CODE_DESC RDCD
    ON RDCD.REF_DATA_CODE_PK = RDC.REF_DATA_CODE_PK
   AND RDCD.LANGUAGE_CODE = 'ENG'
  WHERE RDS.REF_DATA_SET_NAME = 'ROLE_TYPE'
    AND RDS.EFFECTIVE_TO_DATE IS NULL
    AND RDC.EFFECTIVE_TO_DATE = '31-DEC-9999'
)
SELECT
  PR.PARTY_PK,
  PR.PARTY_ROLE_PK,
  PR.MAIN_ROLE_TYPE,
  R.ROLE_TYPE,
  RN.SHORT_DESCRIPTION AS ROLE_NAME,
  PR.PARTY_ROLE_FROM_DATE
FROM AHBRP.PARTY_ROLE PR
JOIN AHBRP.ROLE R
  ON R.ROLE_PK = PR.ROLE_PK
 AND (R.ROLE_EFFECTIVE_TO_DATE IS NULL OR R.ROLE_EFFECTIVE_TO_DATE > SYSDATE)
LEFT JOIN ROLE_NAME RN
  ON RN.CODE = R.ROLE_TYPE
WHERE PR.PARTY_PK IN (__PARTY_KEYS__)
  AND PR.PARTY_ROLE_TO_DATE IS NULL
ORDER BY PR.PARTY_PK, PR.PARTY_ROLE_FROM_DATE, PR.PARTY_ROLE_PK
