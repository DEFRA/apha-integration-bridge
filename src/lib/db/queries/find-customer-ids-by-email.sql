WITH
EMAIL_PARTY AS (
  SELECT PCA.PARTY_PK
  FROM AHBRP.TELECOM_ADDRESS TA
  JOIN AHBRP.PARTY_CONTACT_ADDRESS PCA
    ON PCA.TELECOM_ADDRESS_PK = TA.TELECOM_ADDRESS_PK
   AND PCA.PARTY_CONTACT_TO_DATE IS NULL
  WHERE UPPER(TRIM(TA.INTERNET_EMAIL_ADDRESS)) = :email
    AND TA.TELECOM_ADDRESS_TYPE = 'EMAIL'
    AND TA.TELECOM_ADDRESS_TO_DATE IS NULL
)
SELECT DISTINCT P.PARTY_ID
FROM EMAIL_PARTY EP
JOIN AHBRP.PARTY P
  ON P.PARTY_PK = EP.PARTY_PK
JOIN AHBRP.PARTY_STATE PS
  ON PS.PARTY_PK = P.PARTY_PK
 AND PS.PARTY_STATUS_CODE <> 'INACTIVE'
 AND PS.PARTY_STATE_TO_DTTM IS NULL
JOIN AHBRP.PARTY_VERSION PV
  ON PV.PARTY_PK = P.PARTY_PK
 AND PV.PARTY_TYPE = 'PERSON'
 AND PV.PARTY_VERSION_TO_DATETIME = '31-DEC-9999'
JOIN AHBRP.PERSON PE
  ON PE.PARTY_PK = P.PARTY_PK
WHERE (:surname IS NULL OR UPPER(TRIM(PE.PERSON_FAMILY_NAME)) = :surname)
  AND (
    :postcode IS NULL
    OR EXISTS (
      SELECT 1
      FROM AHBRP.PARTY_CONTACT_ADDRESS APCA
      JOIN AHBRP.ADDRESS A
        ON A.ADDRESS_PK = APCA.ADDRESS_PK
       AND A.ADDRESS_TO_DATE IS NULL
      JOIN AHBRP.BS7666_ADDRESS BA
        ON BA.ADDRESS_PK = A.ADDRESS_PK
      WHERE APCA.PARTY_PK = P.PARTY_PK
        AND APCA.PARTY_CONTACT_TO_DATE IS NULL
        AND REPLACE(UPPER(BA.POSTCODE), ' ') = :postcode
    )
  )
ORDER BY P.PARTY_ID
