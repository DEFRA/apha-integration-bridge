WITH
TARGET_ROLE AS (
  SELECT
    PR.PARTY_PK,
    PR.PARTY_ROLE_PK,
    PR.MAIN_ROLE_TYPE,
    R.ROLE_TYPE
  FROM AHBRP.PARTY_ROLE PR
  JOIN AHBRP.ROLE R
    ON R.ROLE_PK = PR.ROLE_PK
   AND (R.ROLE_EFFECTIVE_TO_DATE IS NULL OR R.ROLE_EFFECTIVE_TO_DATE > SYSDATE)
  WHERE PR.PARTY_PK IN (__PARTY_KEYS__)
    AND PR.PARTY_ROLE_TO_DATE IS NULL
),
INVOLVEMENT AS (
  SELECT
    TR.PARTY_PK,
    TR.MAIN_ROLE_TYPE,
    TR.ROLE_TYPE,
    FI.FEATURE_INVOLVEMENT_TYPE AS INVOLVEMENT_TYPE,
    FI.FEATURE_PK,
    FI.FEATURE_INVOLVEMENT_PK AS HOLDERSHIP_PK,
    CAST(NULL AS VARCHAR2(30)) AS LIVESTOCK_UNIT_ID
  FROM TARGET_ROLE TR
  JOIN AHBRP.FEATURE_INVOLVEMENT FI
    ON FI.PARTY_ROLE_PK = TR.PARTY_ROLE_PK
   AND FI.FEATURE_INVOLVEMENT_TYPE = 'CPHHOLDERSHIP'
   AND FI.FEATURE_INVOLV_TO_DATE IS NULL

  UNION ALL

  SELECT
    TR.PARTY_PK,
    TR.MAIN_ROLE_TYPE,
    TR.ROLE_TYPE,
    FI.FEATURE_INVOLVEMENT_TYPE,
    FI.FEATURE_PK,
    CAST(NULL AS NUMBER),
    CAST(NULL AS VARCHAR2(30))
  FROM TARGET_ROLE TR
  JOIN AHBRP.FEATURE_INVOLVEMENT FI
    ON FI.PARTY_ROLE_PK = TR.PARTY_ROLE_PK
   AND FI.FEATURE_INVOLVEMENT_TYPE = 'OWNEROFLOCATION'
   AND FI.FEATURE_INVOLV_TO_DATE IS NULL

  UNION ALL

  SELECT
    TR.PARTY_PK,
    TR.MAIN_ROLE_TYPE,
    TR.ROLE_TYPE,
    AI.ASSET_INVOLVEMENT_TYPE,
    AL.FEATURE_PK,
    CAST(NULL AS NUMBER),
    LU.UNIT_ID
  FROM TARGET_ROLE TR
  JOIN AHBRP.ASSET_INVOLVEMENT AI
    ON AI.PARTY_ROLE_PK = TR.PARTY_ROLE_PK
   AND AI.ASSET_INVOLVEMENT_TYPE IN ('PRIMARYKEEPEROF', 'SECONDARYKEEPEROF', 'OWNEROF')
   AND AI.ASSET_INVOLVEMENT_TO_DATE IS NULL
  JOIN AHBRP.LIVESTOCK_UNIT LU
    ON LU.ASSET_PK = AI.ASSET_PK
  JOIN AHBRP.ASSET_LOCATION AL
    ON AL.ASSET_PK = AI.ASSET_PK
   AND AL.ASSET_LOCATION_TYPE = 'PRIMARYLOCATION'
   AND AL.ASSET_LOCATION_TO_DATE IS NULL
),
ACTIVE_HOLDERSHIP AS (
  SELECT
    FI.FEATURE_INVOLVEMENT_PK,
    FI.FEATURE_PK,
    FI.CPH
  FROM AHBRP.FEATURE_INVOLVEMENT FI
  JOIN AHBRP.FEATURE_STATE FS
    ON FS.FEATURE_PK = FI.FEATURE_PK
   AND FS.FEATURE_STATUS_CODE <> 'INACTIVE'
   AND FS.FEATURE_STATE_TO_DTTM IS NULL
  JOIN AHBRP.PARTY_ROLE PR
    ON PR.PARTY_ROLE_PK = FI.PARTY_ROLE_PK
   AND PR.PARTY_ROLE_TO_DATE IS NULL
  JOIN AHBRP.PARTY_STATE PS
    ON PS.PARTY_PK = PR.PARTY_PK
   AND PS.PARTY_STATUS_CODE <> 'INACTIVE'
   AND PS.PARTY_STATE_TO_DTTM IS NULL
  WHERE FI.FEATURE_PK IN (SELECT I.FEATURE_PK FROM INVOLVEMENT I)
    AND FI.FEATURE_INVOLVEMENT_TYPE = 'CPHHOLDERSHIP'
    AND FI.FEATURE_INVOLV_TO_DATE IS NULL
    AND EXISTS (
      SELECT 1
      FROM AHBRP.CPH C
      WHERE C.CPH = FI.CPH
        AND C.CORE_ID = FI.VETNET_CORE_ID
    )
),
ROLE_NAME AS (
  SELECT
    RDC.CODE,
    RDCD.SHORT_DESCRIPTION
  FROM AHBRP.REF_DATA_SET RDS
  JOIN AHBRP.REF_DATA_CODE RDC
    ON RDC.REF_DATA_SET_PK = RDS.REF_DATA_SET_PK
  JOIN AHBRP.REF_DATA_CODE_DESC RDCD
    ON RDCD.REF_DATA_CODE_PK = RDC.REF_DATA_CODE_PK
   AND RDCD.LANGUAGE_CODE = 'ENG'
  WHERE RDS.REF_DATA_SET_NAME = 'ROLE_TYPE'
    AND RDS.EFFECTIVE_TO_DATE IS NULL
    AND RDC.EFFECTIVE_TO_DATE = '31-DEC-9999'
)
SELECT DISTINCT
  I.PARTY_PK,
  AH.CPH,
  I.MAIN_ROLE_TYPE,
  I.ROLE_TYPE,
  RN.SHORT_DESCRIPTION AS ROLE_NAME,
  I.INVOLVEMENT_TYPE,
  L.LOCATION_ID,
  I.LIVESTOCK_UNIT_ID
FROM INVOLVEMENT I
JOIN ACTIVE_HOLDERSHIP AH
  ON AH.FEATURE_PK = I.FEATURE_PK
 AND (I.HOLDERSHIP_PK IS NULL OR AH.FEATURE_INVOLVEMENT_PK = I.HOLDERSHIP_PK)
LEFT JOIN AHBRP.LOCATION L
  ON L.FEATURE_PK = I.FEATURE_PK
LEFT JOIN ROLE_NAME RN
  ON RN.CODE = I.ROLE_TYPE
ORDER BY
  I.PARTY_PK,
  AH.CPH,
  I.MAIN_ROLE_TYPE,
  I.ROLE_TYPE,
  I.INVOLVEMENT_TYPE,
  L.LOCATION_ID,
  I.LIVESTOCK_UNIT_ID
