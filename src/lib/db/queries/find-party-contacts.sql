WITH
TARGET_PARTY AS (
  SELECT P.PARTY_PK
  FROM AHBRP.PARTY P
  WHERE P.PARTY_PK IN (__PARTY_KEYS__)
),
CONTACT_LINK AS (
  SELECT
    TP.PARTY_PK,
    PCA.PARTY_CONTACT_ADDRESS_PK,
    CAST(NULL AS NUMBER) AS PARTY_ROLE_PK,
    PCA.TELECOM_ADDRESS_PK,
    PCA.PARTY_CONTACT_FROM_DATE
  FROM TARGET_PARTY TP
  JOIN AHBRP.PARTY_CONTACT_ADDRESS PCA
    ON PCA.PARTY_PK = TP.PARTY_PK
   AND PCA.TELECOM_ADDRESS_PK IS NOT NULL
   AND PCA.PARTY_CONTACT_FROM_DATE <= SYSDATE
   AND (PCA.PARTY_CONTACT_TO_DATE IS NULL OR PCA.PARTY_CONTACT_TO_DATE > SYSDATE)

  UNION ALL

  SELECT
    TP.PARTY_PK,
    PCA.PARTY_CONTACT_ADDRESS_PK,
    PCA.PARTY_ROLE_PK,
    PCA.TELECOM_ADDRESS_PK,
    PCA.PARTY_CONTACT_FROM_DATE
  FROM TARGET_PARTY TP
  JOIN AHBRP.PARTY_ROLE PR
    ON PR.PARTY_PK = TP.PARTY_PK
   AND PR.PARTY_ROLE_FROM_DATE <= SYSDATE
   AND (PR.PARTY_ROLE_TO_DATE IS NULL OR PR.PARTY_ROLE_TO_DATE > SYSDATE)
  JOIN AHBRP.PARTY_CONTACT_ADDRESS PCA
    ON PCA.PARTY_ROLE_PK = PR.PARTY_ROLE_PK
   AND PCA.PARTY_PK IS NULL
   AND PCA.TELECOM_ADDRESS_PK IS NOT NULL
   AND PCA.PARTY_CONTACT_FROM_DATE <= SYSDATE
   AND (PCA.PARTY_CONTACT_TO_DATE IS NULL OR PCA.PARTY_CONTACT_TO_DATE > SYSDATE)
),
CONTACT AS (
  SELECT
    CL.PARTY_PK,
    CL.PARTY_CONTACT_ADDRESS_PK,
    CL.PARTY_ROLE_PK,
    CL.PARTY_CONTACT_FROM_DATE,
    TA.TELECOM_ADDRESS_PK,
    TA.TELECOM_ADDRESS_TYPE,
    CASE TA.TELECOM_ADDRESS_TYPE
      WHEN 'MOBILE' THEN TA.MOBILE_NUMBER
      WHEN 'LANDLINE' THEN TA.TELEPHONE_NUMBER
      WHEN 'EMAIL' THEN TA.INTERNET_EMAIL_ADDRESS
      WHEN 'FAX' THEN TA.FAX_NUMBER
    END AS CONTACT_VALUE,
    TA.TELEPHONE_COUNTRY_CODE,
    TA.EXTENSION_NUMBER,
    AU.ADDRESS_USAGE_TYPE,
    AU.PREFERRED_CONTACT_METHOD_IND,
    ROW_NUMBER() OVER (
      PARTITION BY CL.PARTY_CONTACT_ADDRESS_PK
      ORDER BY
        CASE WHEN AU.PREFERRED_CONTACT_METHOD_IND = 'Y' THEN 0 ELSE 1 END,
        AU.ADDRESS_USAGE_FROM_DATE DESC,
        AU.ADDRESS_USAGE_PK DESC
    ) AS USAGE_ROW
  FROM CONTACT_LINK CL
  JOIN AHBRP.TELECOM_ADDRESS TA
    ON TA.TELECOM_ADDRESS_PK = CL.TELECOM_ADDRESS_PK
   AND TA.TELECOM_ADDRESS_TYPE IN ('MOBILE', 'LANDLINE', 'EMAIL', 'FAX')
   AND TA.TELECOM_ADDRESS_FROM_DATE <= SYSDATE
   AND (TA.TELECOM_ADDRESS_TO_DATE IS NULL OR TA.TELECOM_ADDRESS_TO_DATE > SYSDATE)
  LEFT JOIN AHBRP.ADDRESS_USAGE AU
    ON AU.PARTY_CONTACT_ADDRESS_PK = CL.PARTY_CONTACT_ADDRESS_PK
   AND AU.ADDRESS_USAGE_FROM_DATE <= SYSDATE
   AND (AU.ADDRESS_USAGE_TO_DATE IS NULL OR AU.ADDRESS_USAGE_TO_DATE > SYSDATE)
)
SELECT
  C.PARTY_PK,
  C.PARTY_CONTACT_ADDRESS_PK,
  C.PARTY_ROLE_PK,
  C.TELECOM_ADDRESS_PK,
  C.TELECOM_ADDRESS_TYPE,
  TRIM(C.CONTACT_VALUE) AS CONTACT_VALUE,
  TRIM(C.TELEPHONE_COUNTRY_CODE) AS TELEPHONE_COUNTRY_CODE,
  TRIM(C.EXTENSION_NUMBER) AS EXTENSION_NUMBER,
  TRIM(C.ADDRESS_USAGE_TYPE) AS ADDRESS_USAGE_TYPE,
  TRIM(C.PREFERRED_CONTACT_METHOD_IND) AS PREFERRED_CONTACT_METHOD_IND,
  C.PARTY_CONTACT_FROM_DATE
FROM CONTACT C
WHERE C.USAGE_ROW = 1
ORDER BY C.PARTY_PK, C.PARTY_CONTACT_FROM_DATE, C.PARTY_CONTACT_ADDRESS_PK
