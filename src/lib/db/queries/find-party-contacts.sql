WITH
TARGET_PARTY AS (
  SELECT P.PARTY_PK
  FROM AHBRP.PARTY P
  WHERE P.PARTY_PK IN (__PARTY_KEYS__)
),
CONTACT AS (
  SELECT
    TP.PARTY_PK,
    PCA.PARTY_CONTACT_ADDRESS_PK,
    PCA.PARTY_CONTACT_FROM_DATE,
    TA.TELECOM_ADDRESS_PK,
    TA.TELECOM_ADDRESS_TYPE,
    CASE TA.TELECOM_ADDRESS_TYPE
      WHEN 'MOBILE' THEN TA.MOBILE_NUMBER
      WHEN 'LANDLINE' THEN TA.TELEPHONE_NUMBER
      WHEN 'EMAIL' THEN TA.INTERNET_EMAIL_ADDRESS
      WHEN 'FAX' THEN TA.FAX_NUMBER
    END AS CONTACT_VALUE,
    AU.ADDRESS_USAGE_TYPE,
    AU.PREFERRED_CONTACT_METHOD_IND,
    ROW_NUMBER() OVER (
      PARTITION BY PCA.PARTY_CONTACT_ADDRESS_PK
      ORDER BY
        CASE WHEN AU.PREFERRED_CONTACT_METHOD_IND = 'Y' THEN 0 ELSE 1 END,
        AU.ADDRESS_USAGE_FROM_DATE DESC,
        AU.ADDRESS_USAGE_PK DESC
    ) AS USAGE_ROW
  FROM TARGET_PARTY TP
  JOIN AHBRP.PARTY_CONTACT_ADDRESS PCA
    ON PCA.PARTY_PK = TP.PARTY_PK
   AND PCA.TELECOM_ADDRESS_PK IS NOT NULL
   AND PCA.PARTY_CONTACT_TO_DATE IS NULL
  JOIN AHBRP.TELECOM_ADDRESS TA
    ON TA.TELECOM_ADDRESS_PK = PCA.TELECOM_ADDRESS_PK
   AND TA.TELECOM_ADDRESS_TYPE IN ('MOBILE', 'LANDLINE', 'EMAIL', 'FAX')
   AND TA.TELECOM_ADDRESS_TO_DATE IS NULL
  LEFT JOIN AHBRP.ADDRESS_USAGE AU
    ON AU.PARTY_CONTACT_ADDRESS_PK = PCA.PARTY_CONTACT_ADDRESS_PK
   AND AU.ADDRESS_USAGE_TO_DATE IS NULL
)
SELECT
  C.PARTY_PK,
  C.PARTY_CONTACT_ADDRESS_PK,
  C.TELECOM_ADDRESS_PK,
  C.TELECOM_ADDRESS_TYPE,
  TRIM(C.CONTACT_VALUE) AS CONTACT_VALUE,
  TRIM(C.ADDRESS_USAGE_TYPE) AS ADDRESS_USAGE_TYPE,
  TRIM(C.PREFERRED_CONTACT_METHOD_IND) AS PREFERRED_CONTACT_METHOD_IND,
  C.PARTY_CONTACT_FROM_DATE,
  C.USAGE_ROW
FROM CONTACT C
ORDER BY C.PARTY_PK, C.PARTY_CONTACT_FROM_DATE, C.PARTY_CONTACT_ADDRESS_PK, C.USAGE_ROW
