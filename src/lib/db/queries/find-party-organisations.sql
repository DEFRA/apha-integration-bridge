WITH
TARGET_PARTY AS (
  SELECT P.PARTY_PK
  FROM AHBRP.PARTY P
  WHERE P.PARTY_PK IN (__PARTY_KEYS__)
)
SELECT DISTINCT
  TP.PARTY_PK,
  OP.PARTY_ID AS ORGANISATION_ID
FROM TARGET_PARTY TP
JOIN AHBRP.PARTY_RELATIONSHIP PR
  ON PR.FIRST_PARTY_PK = TP.PARTY_PK
 AND PR.PARTY_RELATION_TO_DATE IS NULL
JOIN AHBRP.PARTY OP
  ON OP.PARTY_PK = PR.SECOND_PARTY_PK
JOIN AHBRP.PARTY_VERSION PV
  ON PV.PARTY_PK = OP.PARTY_PK
 AND PV.PARTY_TYPE = 'ORGANISATION'
 AND PV.PARTY_VERSION_TO_DATETIME = '31-DEC-9999'
JOIN AHBRP.PARTY_STATE PS
  ON PS.PARTY_PK = OP.PARTY_PK
 AND PS.PARTY_STATUS_CODE <> 'INACTIVE'
 AND PS.PARTY_STATE_TO_DTTM IS NULL
ORDER BY TP.PARTY_PK, OP.PARTY_ID
