WITH
TARGET_PARTY AS (
  SELECT
    P.PARTY_PK,
    P.PARTY_ID
  FROM AHBRP.PARTY P
  WHERE P.PARTY_PK IN (__PARTY_KEYS__)
)
SELECT
  TP.PARTY_PK,
  TP.PARTY_ID,
  TRIM(O.ORGANISATION_NAME) AS ORGANISATION_NAME,
  TRIM(O.ORGANISATION_TYPE) AS ORGANISATION_TYPE
FROM TARGET_PARTY TP
JOIN AHBRP.PARTY_VERSION PV
  ON PV.PARTY_PK = TP.PARTY_PK
 AND PV.PARTY_TYPE = 'ORGANISATION'
 AND PV.PARTY_VERSION_TO_DATETIME = '31-DEC-9999'
JOIN AHBRP.ORGANISATION O
  ON O.PARTY_PK = TP.PARTY_PK
ORDER BY TP.PARTY_PK
