WITH
TARGET_FEATURE AS (
  SELECT
    L.FEATURE_PK,
    L.LOCATION_ID
  FROM AHBRP.LOCATION L
  WHERE L.FEATURE_PK IN (__FEATURE_KEYS__)
),
SUPPLIER_INVOLVEMENT AS (
  SELECT
    TF.FEATURE_PK,
    TF.LOCATION_ID,
    LU.UNIT_ID AS LIVESTOCK_UNIT_ID,
    AI.ASSET_INVOLVEMENT_PK AS INVOLVEMENT_PK,
    AI.ASSET_INVOLVEMENT_TYPE AS INVOLVEMENT_TYPE,
    AI.ASSET_INVOLVEMENT_FROM_DATE AS INVOLVEMENT_FROM_DATE,
    AI.PARTY_ROLE_PK
  FROM TARGET_FEATURE TF
  JOIN AHBRP.ASSET_LOCATION AL
    ON AL.FEATURE_PK = TF.FEATURE_PK
   AND AL.ASSET_LOCATION_TYPE = 'PRIMARYLOCATION'
   AND AL.ASSET_LOCATION_FROM_DATE <= SYSDATE
   AND (AL.ASSET_LOCATION_TO_DATE IS NULL OR AL.ASSET_LOCATION_TO_DATE > SYSDATE)
  JOIN AHBRP.LIVESTOCK_UNIT LU
    ON LU.ASSET_PK = AL.ASSET_PK
  JOIN AHBRP.ASSET_INVOLVEMENT AI
    ON AI.ASSET_PK = AL.ASSET_PK
   AND AI.ASSET_INVOLVEMENT_TYPE IN ('OVFOR', 'DPFOR')
   AND AI.ASSET_INVOLVEMENT_FROM_DATE <= SYSDATE
   AND (AI.ASSET_INVOLVEMENT_TO_DATE IS NULL OR AI.ASSET_INVOLVEMENT_TO_DATE > SYSDATE)
)
SELECT
  SI.FEATURE_PK,
  SI.LOCATION_ID,
  SI.LIVESTOCK_UNIT_ID,
  SI.INVOLVEMENT_PK,
  SI.INVOLVEMENT_TYPE,
  SI.INVOLVEMENT_FROM_DATE,
  P.PARTY_PK,
  P.PARTY_ID,
  PV.PARTY_TYPE,
  R.ROLE_TYPE,
  PE.PERSON_TITLE,
  PE.PERSON_GIVEN_NAME,
  PE.PERSON_FAMILY_NAME,
  O.ORGANISATION_NAME
FROM SUPPLIER_INVOLVEMENT SI
JOIN AHBRP.PARTY_ROLE PR
  ON PR.PARTY_ROLE_PK = SI.PARTY_ROLE_PK
 AND PR.PARTY_ROLE_FROM_DATE <= SYSDATE
 AND (PR.PARTY_ROLE_TO_DATE IS NULL OR PR.PARTY_ROLE_TO_DATE > SYSDATE)
JOIN AHBRP.ROLE R
  ON R.ROLE_PK = PR.ROLE_PK
JOIN AHBRP.PARTY P
  ON P.PARTY_PK = PR.PARTY_PK
LEFT JOIN AHBRP.PARTY_VERSION PV
  ON PV.PARTY_PK = P.PARTY_PK
 AND PV.PARTY_VERSION_TO_DATETIME = '31-DEC-9999'
LEFT JOIN AHBRP.PERSON PE
  ON PE.PARTY_PK = P.PARTY_PK
LEFT JOIN AHBRP.ORGANISATION O
  ON O.PARTY_PK = P.PARTY_PK
ORDER BY SI.FEATURE_PK, P.PARTY_ID, SI.LIVESTOCK_UNIT_ID, SI.INVOLVEMENT_TYPE, SI.INVOLVEMENT_PK, PV.PARTY_TYPE
