WITH
TARGET_PARTY AS (
  SELECT P.PARTY_PK
  FROM AHBRP.PARTY P
  WHERE P.PARTY_PK IN (__PARTY_KEYS__)
),
ADDRESS_LINK AS (
  SELECT
    TP.PARTY_PK,
    PCA.PARTY_CONTACT_ADDRESS_PK,
    PCA.ADDRESS_PK,
    PCA.PARTY_CONTACT_FROM_DATE,
    AU.ADDRESS_USAGE_TYPE,
    AU.PREFERRED_CONTACT_METHOD_IND,
    ROW_NUMBER() OVER (
      PARTITION BY PCA.PARTY_CONTACT_ADDRESS_PK
      ORDER BY
        CASE WHEN AU.PREFERRED_CONTACT_METHOD_IND = 'Y' THEN 0 ELSE 1 END,
        AU.ADDRESS_USAGE_FROM_DATE DESC,
        AU.ADDRESS_USAGE_PK DESC
    ) AS USAGE_ROW
  FROM TARGET_PARTY TP
  JOIN AHBRP.PARTY_CONTACT_ADDRESS PCA
    ON PCA.PARTY_PK = TP.PARTY_PK
   AND PCA.ADDRESS_PK IS NOT NULL
   AND PCA.PARTY_CONTACT_TO_DATE IS NULL
  JOIN AHBRP.ADDRESS A
    ON A.ADDRESS_PK = PCA.ADDRESS_PK
   AND A.ADDRESS_TO_DATE IS NULL
  LEFT JOIN AHBRP.ADDRESS_USAGE AU
    ON AU.PARTY_CONTACT_ADDRESS_PK = PCA.PARTY_CONTACT_ADDRESS_PK
   AND AU.ADDRESS_USAGE_TO_DATE IS NULL
),
COUNTY_LOOKUP AS (
  SELECT DISTINCT
    RDC.CODE,
    RDCD.SHORT_DESCRIPTION
  FROM AHBRP.REF_DATA_SET RDS
  JOIN AHBRP.REF_DATA_CODE RDC
    ON RDC.REF_DATA_SET_PK = RDS.REF_DATA_SET_PK
  JOIN AHBRP.REF_DATA_CODE_DESC RDCD
    ON RDCD.REF_DATA_CODE_PK = RDC.REF_DATA_CODE_PK
  WHERE RDS.REF_DATA_SET_NAME = 'COUNTY'
    AND RDS.EFFECTIVE_TO_DATE IS NULL
    AND RDC.EFFECTIVE_TO_DATE = '31-DEC-9999'
    AND RDCD.LANGUAGE_CODE = 'ENG'
)
SELECT
  AL.PARTY_PK,
  AL.PARTY_CONTACT_ADDRESS_PK,
  AL.ADDRESS_PK,
  AL.PARTY_CONTACT_FROM_DATE,
  BA.PAON_START_NUMBER,
  BA.PAON_START_NUMBER_SUFFIX,
  BA.PAON_END_NUMBER,
  BA.PAON_END_NUMBER_SUFFIX,
  BA.PAON_DESCRIPTION,
  BA.SAON_DESCRIPTION,
  BA.SAON_START_NUMBER,
  BA.SAON_START_NUMBER_SUFFIX,
  BA.SAON_END_NUMBER,
  BA.SAON_END_NUMBER_SUFFIX,
  BA.STREET,
  BA.LOCALITY,
  BA.TOWN,
  COUNTY_LOOKUP.SHORT_DESCRIPTION AS COUNTY,
  BA.POSTCODE,
  BA.UK_INTERNAL_CODE,
  BA.COUNTRY_CODE,
  TRIM(AL.ADDRESS_USAGE_TYPE) AS ADDRESS_USAGE_TYPE,
  TRIM(AL.PREFERRED_CONTACT_METHOD_IND) AS PREFERRED_CONTACT_METHOD_IND
FROM ADDRESS_LINK AL
JOIN AHBRP.BS7666_ADDRESS BA
  ON BA.ADDRESS_PK = AL.ADDRESS_PK
LEFT JOIN COUNTY_LOOKUP
  ON COUNTY_LOOKUP.CODE = BA.ADMINISTRATIVE_AREA
WHERE AL.USAGE_ROW = 1
ORDER BY AL.PARTY_PK, AL.PARTY_CONTACT_FROM_DATE, AL.PARTY_CONTACT_ADDRESS_PK
